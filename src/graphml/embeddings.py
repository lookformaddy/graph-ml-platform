"""Node embeddings: random walks + skip-gram with negative sampling.

From scratch, pure stdlib — no torch, no numpy. Walks are generated by
uniform random neighbour sampling; the skip-gram trainer learns an
input and an output vector per node with sigmoid updates and negative
sampling from a degree^0.75 unigram distribution. Deterministic given
the seed: the same graph + seed always yields identical embeddings,
which is what makes embedding-drift monitoring meaningful.
"""

from __future__ import annotations

import math
import random

from graphml.graph import Graph


def _sigmoid(x: float) -> float:
    if x >= 0:
        return 1.0 / (1.0 + math.exp(-x))
    ex = math.exp(x)
    return ex / (1.0 + ex)


def random_walks(graph: Graph, walk_length: int = 10,
                 walks_per_node: int = 5, seed: int = 0) -> list[list[int]]:
    """Uniform random walks, one batch per node per round."""
    rng = random.Random(seed)
    walks: list[list[int]] = []
    for _ in range(walks_per_node):
        for start in range(graph.n_nodes):
            walk = [start]
            current = start
            for _ in range(walk_length - 1):
                nbrs = graph.neighbors(current)
                if not nbrs:
                    break
                current = rng.choice(nbrs)
                walk.append(current)
            walks.append(walk)
    return walks


class SkipGramEmbeddings:
    """Small skip-gram trainer with negative sampling."""

    def __init__(self, dim: int = 16, window: int = 2, negatives: int = 4,
                 epochs: int = 2, lr: float = 0.05, seed: int = 0) -> None:
        self.dim = dim
        self.window = window
        self.negatives = negatives
        self.epochs = epochs
        self.lr = lr
        self.seed = seed
        self.vectors: dict[int, list[float]] = {}
        self._output: dict[int, list[float]] = {}

    def fit(self, graph: Graph,
            walks: list[list[int]] | None = None) -> "SkipGramEmbeddings":
        rng = random.Random(self.seed)
        if walks is None:
            walks = random_walks(graph, seed=self.seed)
        n = graph.n_nodes
        self.vectors = {i: [rng.gauss(0.0, 0.1) for _ in range(self.dim)]
                        for i in range(n)}
        self._output = {i: [0.0] * self.dim for i in range(n)}

        # Negative-sampling distribution: degree^0.75.
        weights = [graph.degree(i) ** 0.75 + 1e-6 for i in range(n)]
        total_w = sum(weights)
        cumulative = []
        running = 0.0
        for w in weights:
            running += w / total_w
            cumulative.append(running)

        def sample_negative(exclude: set[int]) -> int:
            for _ in range(10):
                r = rng.random()
                lo, hi = 0, n - 1
                while lo < hi:
                    mid = (lo + hi) // 2
                    if cumulative[mid] < r:
                        lo = mid + 1
                    else:
                        hi = mid
                if lo not in exclude:
                    return lo
            return rng.randrange(n)

        for _epoch in range(self.epochs):
            for walk in walks:
                for pos, centre in enumerate(walk):
                    lo = max(0, pos - self.window)
                    hi = min(len(walk), pos + self.window + 1)
                    for j in range(lo, hi):
                        if j == pos:
                            continue
                        context = walk[j]
                        targets = [(context, 1)]
                        exclude = {centre, context}
                        for _ in range(self.negatives):
                            targets.append((sample_negative(exclude), 0))
                        for target, label in targets:
                            vec_c = self.vectors[centre]
                            vec_o = self._output[target]
                            dot = sum(vec_c[d] * vec_o[d]
                                      for d in range(self.dim))
                            g = (label - _sigmoid(dot)) * self.lr
                            for d in range(self.dim):
                                grad_c = g * vec_o[d]
                                grad_o = g * vec_c[d]
                                vec_c[d] += grad_c
                                vec_o[d] += grad_o
        return self

    def embedding(self, node: int) -> list[float]:
        return list(self.vectors[node])

    def all_embeddings(self) -> dict[int, list[float]]:
        return {node: list(vec) for node, vec in self.vectors.items()}

    def cosine(self, u: int, v: int) -> float:
        a, b = self.vectors[u], self.vectors[v]
        dot = sum(x * y for x, y in zip(a, b))
        na = math.sqrt(sum(x * x for x in a))
        nb = math.sqrt(sum(y * y for y in b))
        if na == 0.0 or nb == 0.0:
            return 0.0
        return max(-1.0, min(1.0, dot / (na * nb)))

    def nearest(self, node: int, k: int = 5) -> list[tuple[int, float]]:
        scored = [(other, self.cosine(node, other))
                  for other in self.vectors if other != node]
        scored.sort(key=lambda t: t[1], reverse=True)
        return scored[:k]
